design = lambda: from_ascii(DESIGN)
technology = lambda: from_ascii(TECHNOLOGY)
evolution = lambda: from_ascii(EVOLUTION)

def showcase_platform():
    """A dashboard screen for the 'what's next' card."""
    k = Canvas(48, 40)
    k.rect(4, 3, 31, 44, 'S'); k.rect(5, 4, 30, 43, 'L')
    k.rect(5, 4, 30, 11, 'M')                                     # sidebar
    for r in (8, 11, 14, 17): k.rect(r, 6, r, 9, 'B')
    k.rect(8, 14, 13, 24, 'B'); k.rect(8, 27, 13, 33, 'B'); k.rect(8, 36, 13, 41, 'S')   # tiles
    for i, h in enumerate((3, 5, 4, 7, 6, 9, 8, 11)):             # chart
        k.rect(28 - h, 15 + i * 3, 28, 16 + i * 3, 'B' if i < 7 else 'S')
    k.rect(32, 21, 34, 26, 'M'); k.rect(35, 15, 35, 32, 'B')       # stand
    return k

ICONS = {'icon-strategy': strategy(), 'icon-design': design(), 'icon-technology': technology(),
         'icon-evolution': evolution(), 'platform': showcase_platform()}

def main(path):
    src = json.load(open(path))
    out = {}
    for name, asset in src.items():
        cells = []
        for g in asset['groups'].values():
            t = TONE_OF_HEX[g['fill'].upper()]
            for p in g['cells'].split(' '):
                r, c = p.split(','); cells.append(f'{r},{c},{t}')
        out[name] = {'cols': asset['cols'], 'rows': asset['rows'], 'cells': ' '.join(cells)}
    for name, k in ICONS.items():
        out[name] = {'cols': k.cols, 'rows': k.rows, 'cells': k.cells()}
        print(name); print(k.ascii()); print()
    body = ',\n'.join(f'  {json.dumps(n)}: {json.dumps(a)}' for n, a in out.items())
    open('src/data/pixel-art.js', 'w').write(
        '/* Generated by scripts/build-pixel-art.py: do not edit by hand.\n'
        '   Cells are "row,col,tone" (1-indexed); tones S shadow, B body,\n'
        '   M mid, L light, per the 3Projects pixel-grid system. */\n'
        f'export const PIXEL_ART = {{\n{body},\n}}\n')

main(sys.argv[1])
