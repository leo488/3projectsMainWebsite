"""Builds src/data/pixel-art.js from the brand illustration package. Every
asset is a grid of cells in four tones (S shadow, B body, M mid, L light),
per the 3Projects pixel-grid illustration system.

    python3 scripts/build-pixel-art.py <illustrations.json> [names...]
"""
import json
import sys

TONE_OF_HEX = {'#0031B8': 'S', '#004BFF': 'B', '#6F95FF': 'M', '#A3C0FF': 'L'}
DEFAULT_NAMES = ('hand-phone', 'pos-terminal')


def main(path, names):
    src = json.load(open(path))
    out = {}
    for name in names:
        asset = src[name]
        cells = []
        for g in asset['groups'].values():
            t = TONE_OF_HEX[g['fill'].upper()]
            for p in g['cells'].split(' '):
                r, c = p.split(',')
                cells.append(f'{r},{c},{t}')
        out[name] = {'cols': asset['cols'], 'rows': asset['rows'], 'cells': ' '.join(cells)}
    body = ',\n'.join(f'  {json.dumps(n)}: {json.dumps(a)}' for n, a in out.items())
    open('src/data/pixel-art.js', 'w').write(
        '/* Generated by scripts/build-pixel-art.py: do not edit by hand.\n'
        '   Cells are "row,col,tone" (1-indexed); tones S shadow, B body,\n'
        '   M mid, L light, per the 3Projects pixel-grid system. */\n'
        f'export const PIXEL_ART = {{\n{body},\n}}\n')


main(sys.argv[1], sys.argv[2:] or DEFAULT_NAMES)
