"""Builds src/data/pixel-art.js from the brand illustration package and
the house icons drawn below. Every asset is a grid of cells in four
tones (S shadow, B body, M mid, L light), per the 3Projects pixel-grid
illustration system. Run: python3 scripts/build-pixel-art.py <illustrations.json>"""
import json, math, sys

TONE_OF_HEX = {'#0031B8': 'S', '#004BFF': 'B', '#6F95FF': 'M', '#A3C0FF': 'L'}

class Canvas:
    def __init__(self, cols, rows):
        self.cols, self.rows = cols, rows
        self.g = [['.'] * cols for _ in range(rows)]
    def set(self, r, c, t):
        if 0 <= r < self.rows and 0 <= c < self.cols: self.g[r][c] = t
    def rect(self, r0, c0, r1, c1, t):
        for r in range(r0, r1 + 1):
            for c in range(c0, c1 + 1): self.set(r, c, t)
    def disc(self, cr, cc, rad, t):
        for r in range(self.rows):
            for c in range(self.cols):
                if (r - cr) ** 2 + (c - cc) ** 2 <= rad * rad: self.set(r, c, t)
    def ring(self, cr, cc, rad, t, width=1.0):
        for r in range(self.rows):
            for c in range(self.cols):
                d = math.hypot(r - cr, c - cc)
                if rad - width < d <= rad: self.set(r, c, t)
    def line(self, r0, c0, r1, c1, t, thick=1):
        n = max(abs(r1 - r0), abs(c1 - c0)) or 1
        for i in range(n + 1):
            r = round(r0 + (r1 - r0) * i / n); c = round(c0 + (c1 - c0) * i / n)
            self.rect(r, c, r + thick - 1, c + thick - 1, t)
    def ascii(self): return '\n'.join(''.join(row) for row in self.g)
    def cells(self):
        return ' '.join(f'{r+1},{c+1},{t}' for r, row in enumerate(self.g) for c, t in enumerate(row) if t != '.')

def from_ascii(art):
    rows = [r for r in art.strip('\n').split('\n')]
    k = Canvas(24, len(rows))
    for r, row in enumerate(rows):
        assert len(row) == 24, (len(row), row)
        for c, t in enumerate(row):
            if t != '.': k.set(r, c, t)
    return k

